    /// `enable_mdns` has to actually reach the behaviour.
    ///
    /// It used to be a config field that nothing read: mDNS was constructed
    /// unconditionally, so a local cluster kept rediscovering peers by
    /// broadcast even when the discovery paths a deployment depends on were
    /// broken. That made local runs unable to reproduce production, which is
    /// how an outage went unnoticed until it hit the real network.
    #[cfg(not(target_arch = "wasm32"))]
    #[tokio::test]
    async fn mdns_is_absent_when_disabled_and_present_when_enabled() {
        let keypair = Keypair::generate_ed25519();
        let local_peer_id = keypair.public().to_peer_id();

        let off = NodeBehaviour::new(
            local_peer_id,
            &keypair,
            BehaviourConfig {
                enable_mdns: false,
                ..BehaviourConfig::default()
            },
            None,
        )
        .unwrap();
        assert!(
            off.mdns.as_ref().is_none(),
            "enable_mdns=false must not construct an mDNS behaviour"
        );

        let on = NodeBehaviour::new(
            local_peer_id,
            &keypair,
            BehaviourConfig {
                enable_mdns: true,
                ..BehaviourConfig::default()
            },
            None,
        )
        .unwrap();
        assert!(
            on.mdns.as_ref().is_some(),
            "enable_mdns=true must enable it"
        );
    }

    /// The NAT-traversal behaviours must follow the flag, both ways.
    ///
    /// Same failure mode as `enable_mdns`, which sat in the config being read
    /// by nobody: a flag that silently does nothing is worse than no flag,
    /// because it makes a deployment look configurable when it is not.
    #[cfg(not(target_arch = "wasm32"))]
    #[tokio::test]
    async fn nat_traversal_behaviours_follow_the_flag() {
        let keypair = Keypair::generate_ed25519();
        let local_peer_id = keypair.public().to_peer_id();

        let off = NodeBehaviour::new(
            local_peer_id,
            &keypair,
            BehaviourConfig {
                enable_nat_traversal: false,
                ..BehaviourConfig::default()
            },
            None,
        )
        .unwrap();
        assert!(off.autonat_client.as_ref().is_none());
        assert!(off.autonat_server.as_ref().is_none());
        assert!(off.relay_server.as_ref().is_none());
        assert!(off.dcutr.as_ref().is_none());

        let on = NodeBehaviour::new(
            local_peer_id,
            &keypair,
            BehaviourConfig {
                enable_nat_traversal: true,
                ..BehaviourConfig::default()
            },
            None,
        )
        .unwrap();
        assert!(on.autonat_client.as_ref().is_some());
        assert!(on.autonat_server.as_ref().is_some());
        assert!(on.relay_server.as_ref().is_some());
        assert!(on.dcutr.as_ref().is_some());
    }

    /// The relay client only exists when its transport half was built too.
    ///
    /// `relay::client::new` returns a transport and a behaviour that are
    /// useless apart: the behaviour negotiates a reservation the transport
    /// would then have to dial through. Enabling one without the other would
    /// advertise a circuit address nothing can actually dial.
    #[cfg(not(target_arch = "wasm32"))]
    #[tokio::test]
    async fn relay_client_is_absent_unless_its_transport_half_is_supplied() {
        let keypair = Keypair::generate_ed25519();
        let local_peer_id = keypair.public().to_peer_id();

        let without =
            NodeBehaviour::new(local_peer_id, &keypair, BehaviourConfig::default(), None).unwrap();
        assert!(without.relay_client.as_ref().is_none());

        let (_transport, client) = relay::client::new(local_peer_id);
        let with = NodeBehaviour::new(
            local_peer_id,
            &keypair,
            BehaviourConfig::default(),
            Some(client),
        )
        .unwrap();
        assert!(with.relay_client.as_ref().is_some());
    }

    /// Passing a relay client while NAT traversal is off must not enable it.
    #[cfg(not(target_arch = "wasm32"))]
